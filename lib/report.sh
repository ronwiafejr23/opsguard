# Daily HTML report: current health, 24h trends, services, backups and security.

esc() { html_escape <<< "$1"; }

report_heading() {
  printf '<h3 style="border-bottom:1px solid #d9e2ec;padding-bottom:4px;margin-top:28px">%s</h3>\n' "$1"
}

report_row() {
  printf '<tr><td style="padding:4px 16px 4px 0;color:#52606d">%s</td><td style="padding:4px 0">%s</td></tr>\n' "$1" "$2"
}

# report_pct VALUE THRESHOLD - red when at/over threshold, green otherwise.
report_pct() {
  if (( $1 >= $2 )); then
    printf '<b style="color:#c62828">%s%%</b>' "$1"
  else
    printf '<span style="color:#2e7d32">%s%%</span>' "$1"
  fi
}

report_pre() {
  printf '<pre style="background:#f5f7fa;padding:10px;border-radius:4px;font-size:12px;overflow-x:auto">%s</pre>\n' \
    "$(esc "${1:-None}")"
}

# Average and peak of each metric over the last 24 hours, as table rows.
report_trends() {
  local metrics="$STATE_DIR/metrics.csv" since
  since=$(( $(date +%s) - 86400 ))
  if [[ ! -f "$metrics" ]]; then
    echo '<tr><td colspan="3">No data yet. Trends appear once "opsguard check" has been running.</td></tr>'
    return
  fi
  awk -F, -v s="$since" '
    $1 >= s { n++; for (i = 2; i <= 4; i++) { sum[i] += $i; if ($i > max[i]) max[i] = $i } }
    END {
      if (!n) { print "<tr><td colspan=\"3\">No samples in the last 24 hours</td></tr>"; exit }
      split("CPU|Memory|Disk (first mount)", name, "|")
      for (i = 2; i <= 4; i++)
        printf "<tr><td style=\"padding:4px 16px 4px 0\">%s</td><td>%d%%</td><td>%d%%</td></tr>\n", name[i-1], sum[i]/n, max[i]
      printf "<tr><td colspan=\"3\" style=\"color:#7b8794;font-size:12px\">%d samples</td></tr>\n", n
    }' "$metrics"
}

build_report() {
  local cpu mem mount disk svc state failed accepted roots last_backup backup_count
  cpu=$(cpu_usage)
  mem=$(mem_usage)
  failed=$(failed_logins_by_ip "24 hours ago" | head -10)
  accepted=$(accepted_logins "24 hours ago" | head -10)
  roots=$(root_logins "24 hours ago" | grep -c . || true)
  last_backup=$(cat "$STATE_DIR/last_backup" 2>/dev/null || echo "never")
  backup_count=$(find "$BACKUP_DIR/daily" -mindepth 1 -maxdepth 1 -type d -name "$BACKUP_NAME_PATTERN" 2>/dev/null | wc -l)

  cat <<EOF
<!doctype html>
<html><head><meta charset="utf-8"><title>opsguard report - $(esc "$HOST_LABEL")</title></head>
<body style="font-family:Arial,Helvetica,sans-serif;color:#1f2933;max-width:720px;margin:24px auto;padding:0 16px">
<h2 style="margin-bottom:4px">opsguard daily report</h2>
<p style="color:#52606d;margin-top:0">$(esc "$HOST_LABEL") &middot; $(date '+%A %d %B %Y, %H:%M %Z')</p>
EOF

  report_heading "System"
  echo '<table>'
  report_row "Uptime" "$(esc "$(uptime -p 2>/dev/null || uptime)")"
  report_row "OS" "$(esc "$(. /etc/os-release 2>/dev/null && echo "$PRETTY_NAME")")"
  report_row "Kernel" "$(esc "$(uname -r)")"
  report_row "Load (1/5/15 min)" "$(cut -d' ' -f1-3 /proc/loadavg)"
  report_row "CPU now" "$(report_pct "$cpu" "$CPU_THRESHOLD")"
  report_row "Memory now" "$(report_pct "$mem" "$MEM_THRESHOLD")"
  for mount in $DISK_MOUNTS; do
    disk=$(disk_usage "$mount")
    [[ -n "$disk" ]] && report_row "Disk $(esc "$mount")" \
      "$(report_pct "$disk" "$DISK_THRESHOLD") ($(df -hP "$mount" | awk 'NR==2 {print $4 " free of " $2}'))"
  done
  echo '</table>'

  report_heading "Last 24 hours"
  echo '<table><tr><th align="left" style="padding-right:16px">Metric</th><th align="left" style="padding-right:16px">Average</th><th align="left">Peak</th></tr>'
  report_trends
  echo '</table>'

  if [[ -n "$SERVICES" ]]; then
    report_heading "Services"
    echo '<table>'
    for svc in $SERVICES; do
      state=$(systemctl is-active "$svc" 2>/dev/null || true)
      if [[ "$state" == active ]]; then
        report_row "$(esc "$svc")" '<span style="color:#2e7d32">active</span>'
      else
        report_row "$(esc "$svc")" "<b style=\"color:#c62828\">$(esc "${state:-unknown}")</b>"
      fi
    done
    echo '</table>'
  fi

  report_heading "Backups"
  echo '<table>'
  report_row "Last backup" "$(esc "$last_backup")"
  report_row "Daily backups kept" "$backup_count (limit $KEEP_DAILY)"
  report_row "Total backup size" "$(du -sh "$BACKUP_DIR" 2>/dev/null | cut -f1 || echo 0)"
  report_row "Off-site copy" "$(esc "${REMOTE_BACKUP_TARGET:-not configured}")"
  echo '</table>'

  report_heading "Security (last 24 hours)"
  echo '<p>Failed SSH logins by IP (top 10):</p>'
  report_pre "$failed"
  echo '<p>Successful SSH logins:</p>'
  report_pre "$accepted"
  echo "<p>Direct root logins: <b>$roots</b></p>"

  cat <<EOF
<p style="color:#7b8794;font-size:12px;margin-top:32px">Generated by opsguard $OPSGUARD_VERSION. Log: $(esc "$LOG_FILE")</p>
</body></html>
EOF
}

run_report() {
  local file failed_total
  file="$STATE_DIR/report-$(date +%F).html"
  build_report > "$file"
  log INFO "report written to $file"

  send_email "[opsguard] Daily report for $HOST_LABEL - $(date +%F)" "$(<"$file")" text/html

  failed_total=$(failed_logins_by_ip "24 hours ago" | awk '{s += $1} END {print s + 0}')
  send_webhook ":bar_chart: *[$HOST_LABEL] Daily report*
CPU $(cpu_usage)% | Memory $(mem_usage)% | Disk / $(disk_usage /)%
Last backup: $(cat "$STATE_DIR/last_backup" 2>/dev/null || echo never)
Failed SSH logins (24h): $failed_total
Full report: $file"

  find "$STATE_DIR" -maxdepth 1 -name 'report-*.html' -mtime +30 -delete
}
